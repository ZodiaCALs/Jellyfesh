//! Writes and checks `tests/contract/lyrics-cursor.json` at the repository
//! root: timelines from a few golden fixtures with the cursor and
//! `next_change` at every boundary, one millisecond either side, and midway.
//!
//! Every shell that draws lyrics (Swift, Kotlin, C#, GTK) replays this file in
//! its own tests, so the per-frame lookups cannot drift from the core's
//! (docs/architecture.md, "Lyrics without per-frame FFI"). To accept a
//! deliberate change, run `UPDATE_GOLDEN=1 cargo test -p jf-lyrics --test
//! contract` and review the diff.

use std::collections::BTreeSet;
use std::path::Path;

use jf_lyrics::{LyricTimeline, parse};
use serde_json::{Value, json};

const FIXTURES: [&str; 4] = [
    "lrc/basic.lrc",
    "lrc/enhanced_words.lrc",
    "ttml/word_timed_duet.ttml",
    "ttml/background.ttml",
];

fn queries(tl: &LyricTimeline) -> Vec<u32> {
    let mut edges: BTreeSet<u32> = BTreeSet::new();
    for list in [
        &tl.segment_starts,
        &tl.line_starts,
        &tl.line_ends,
        &tl.word_starts,
        &tl.word_ends,
    ] {
        edges.extend(list.iter().copied().filter(|&e| e != u32::MAX));
    }
    let sorted: Vec<u32> = edges.iter().copied().collect();
    let mut times: BTreeSet<u32> = BTreeSet::from([0]);
    for &e in &sorted {
        times.extend([e.saturating_sub(1), e, e.saturating_add(1)]);
    }
    for pair in sorted.windows(2) {
        times.insert(pair[0] + (pair[1] - pair[0]) / 2);
    }
    if let Some(&last) = sorted.last() {
        times.insert(last.saturating_add(10_000));
    }
    times.into_iter().collect()
}

fn build() -> Value {
    let golden = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden");
    let cases: Vec<Value> = FIXTURES
        .iter()
        .map(|fixture| {
            let text = std::fs::read_to_string(golden.join(fixture)).expect("fixture");
            let tl = parse(&text, None).expect("fixture parses").timeline();
            let rows: Vec<Value> = queries(&tl)
                .into_iter()
                .map(|t| {
                    let c = tl.cursor(t);
                    json!({
                        "t": t,
                        "line": c.line,
                        "word": c.word,
                        "word_progress": (f64::from(c.word_progress) * 1e6).round() / 1e6,
                        "next_change": tl.next_change(t),
                    })
                })
                .collect();
            json!({ "name": fixture, "timeline": tl, "queries": rows })
        })
        .collect();
    json!({
        "about": "Lyrics cursor contract. For each timeline, cursor(t) must give line, word and word_progress \
                  (within 1e-6), and next_change(t) the given time (null for none). Generated by \
                  core/jf-lyrics/tests/contract.rs from the golden fixtures; every shell replays it.",
        "version": 1,
        "cases": cases,
    })
}

#[test]
fn contract_vectors_match() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/contract/lyrics-cursor.json");
    let fresh = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    if std::env::var("UPDATE_GOLDEN").is_ok_and(|v| v == "1") {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let stored = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e} (run with UPDATE_GOLDEN=1 to create it)", path.display()));
    assert!(
        stored.replace("\r\n", "\n") == fresh,
        "{} is out of date: run UPDATE_GOLDEN=1 cargo test -p jf-lyrics --test contract and review the diff",
        path.display()
    );
}
