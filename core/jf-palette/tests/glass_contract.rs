//! `tests/contract/glass-alpha.json`: the glass alpha for the transparency
//! setting, recorded from `jf_palette::glass_alpha`. Every app that draws
//! glass with an alpha replays these cases (within `tolerance`).
//!
//! After changing the function, run
//! `UPDATE_GOLDEN=1 cargo test -p jf-palette --test glass_contract` and review
//! the diff.

use std::path::PathBuf;

/// The tokens' glass alphas (Clear, Mist, Veil; light and dark) and the ends.
const ALPHAS: [f32; 8] = [0.0, 0.3, 0.36, 0.42, 0.5, 0.62, 0.68, 1.0];
/// The setting's range, the default, and values outside it (clamped).
const TRANSPARENCIES: [f32; 11] = [-0.5, 0.0, 0.1, 0.25, 0.4, 0.5, 0.6, 0.75, 0.9, 1.0, 1.5];

fn contract() -> String {
    let mut rows = Vec::new();
    for alpha in ALPHAS {
        for transparency in TRANSPARENCIES {
            let expected = f64::from(jf_palette::glass_alpha(alpha, transparency));
            let expected = (expected * 1e6).round() / 1e6;
            rows.push(format!("    [{alpha}, {transparency}, {expected}]"));
        }
    }
    format!(
        "{{\n  \"about\": \"Glass alpha for the transparency setting, recorded from jf_palette::glass_alpha \
         (core/jf-palette/src/theme.rs). Each case is [token_alpha, transparency, expected]; a port must \
         return expected within tolerance. Generated by core/jf-palette/tests/glass_contract.rs.\",\n  \
         \"version\": 1,\n  \"tolerance\": 0.00001,\n  \"cases\": [\n{}\n  ]\n}}\n",
        rows.join(",\n")
    )
}

#[test]
fn the_glass_alpha_contract_matches_the_function() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/contract/glass-alpha.json");
    let want = contract();
    if std::env::var("UPDATE_GOLDEN").is_ok_and(|v| v == "1") {
        std::fs::write(&path, &want).unwrap();
    }
    let have = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e} (run with UPDATE_GOLDEN=1 to create it)", path.display()));
    assert!(
        have == want,
        "{} is out of date: run UPDATE_GOLDEN=1 cargo test -p jf-palette --test glass_contract and review the diff",
        path.display()
    );
    // The file is valid JSON with every case.
    let json: serde_json::Value = serde_json::from_str(&have).unwrap();
    assert_eq!(
        json["cases"].as_array().unwrap().len(),
        ALPHAS.len() * TRANSPARENCIES.len()
    );
}
