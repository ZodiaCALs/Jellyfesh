//! Writes and checks `tests/contract/lyrics-bar.json`: what `jf_core::lyrics_bar` (the one-line
//! lyrics bar and Desktop Lyrics, ADR-0022 §6) gives for invented lyrics at many times. Each case
//! carries the flat `LyricTimeline` arrays, so a port needs no lyrics parser. Every shell's port
//! replays it. To accept a deliberate change, run
//! `UPDATE_GOLDEN=1 cargo test -p jf-ffi --test lyrics_bar_contract` and review the diff.

use std::path::Path;

use jf_core::{LyricTimeline, lyrics_bar};
use serde_json::{Value, json};

/// Invented lyrics for the contract (not from any song).
const CASES: &[(&str, &str)] = &[
    (
        "word-timed lines with a gap",
        "[00:01.00]<00:01.00>one <00:01.50>two <00:02.00>\n\
         [00:04.00]<00:04.00>three <00:04.40>four <00:05.00>\n\
         [00:08.00]<00:08.00>five <00:08.30>six\n",
    ),
    (
        "lines without words",
        "[00:00.50]first plain line\n[00:03.00]second plain line\n[00:03.00]same start\n[00:06.25]last\n",
    ),
    (
        "zero-length words and a long word",
        "[00:02.00]<00:02.00>a <00:02.00>b <00:02.10>long <00:07.10>\n[00:09.00]<00:09.00>end <00:09.00>\n",
    ),
];

fn timeline(text: &str) -> LyricTimeline {
    jf_lyrics::parse(text, Some(jf_lyrics::Format::Lrc))
        .expect("the invented lyrics parse")
        .timeline()
}

fn times(tl: &LyricTimeline) -> Vec<u32> {
    let mut times = vec![0, u32::MAX - 1];
    for &t in tl
        .line_starts
        .iter()
        .chain(&tl.line_ends)
        .chain(&tl.word_starts)
        .chain(&tl.word_ends)
    {
        if t != u32::MAX {
            times.extend([t.saturating_sub(1), t, t.saturating_add(1), t.saturating_add(125)]);
        }
    }
    times.sort_unstable();
    times.dedup();
    times
}

/// A fraction rounded to millionths, so the file reads well and parses back exactly; ports
/// compare within 1e-6.
fn micro(x: f32) -> f64 {
    (f64::from(x) * 1e6).round() / 1e6
}

fn contract() -> Value {
    let cases: Vec<Value> = CASES
        .iter()
        .map(|(name, text)| {
            let tl = timeline(text);
            let queries: Vec<Value> = times(&tl)
                .into_iter()
                .map(|t| {
                    let bar = lyrics_bar(&tl, t);
                    let words: Vec<f64> = bar.words.iter().map(|&w| micro(w)).collect();
                    json!({
                        "t": t,
                        "line": bar.line,
                        "next": bar.next,
                        "words": words,
                        "line_progress": micro(bar.line_progress),
                    })
                })
                .collect();
            json!({ "name": name, "timeline": tl, "queries": queries })
        })
        .collect();
    json!({
        "about": "Lyrics bar contract, recorded from jf_core::lyrics_bar (core/jf-core/src/timing.rs) on \
                  invented lyrics. For each case's timeline (the LyricTimeline arrays), lyrics_bar(t) must give \
                  line and next (null for none), words (each within 1e-6) and line_progress (within 1e-6); the \
                  file rounds them to millionths. \
                  Generated by core/jf-ffi/tests/lyrics_bar_contract.rs; every shell's port replays it.",
        "version": 1,
        "cases": cases,
    })
}

/// One query per line, so the file stays readable and diffs well.
fn build() -> String {
    let value = contract();
    let compact = |v: &Value| serde_json::to_string(v).unwrap();
    let mut out = String::from("{\n");
    out += &format!("  \"about\": {},\n", compact(&value["about"]));
    out += &format!("  \"version\": {},\n", value["version"]);
    out += "  \"cases\": [\n";
    let cases = value["cases"].as_array().unwrap();
    for (i, case) in cases.iter().enumerate() {
        out += &format!(
            "    {{\"name\": {}, \"timeline\": {}, \"queries\": [\n",
            compact(&case["name"]),
            compact(&case["timeline"])
        );
        let queries = case["queries"].as_array().unwrap();
        for (j, query) in queries.iter().enumerate() {
            let comma = if j + 1 == queries.len() { "" } else { "," };
            out += &format!("      {}{comma}\n", compact(query));
        }
        let comma = if i + 1 == cases.len() { "" } else { "," };
        out += &format!("    ]}}{comma}\n");
    }
    out += "  ]\n}\n";
    out
}

#[test]
fn lyrics_bar_contract_is_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/contract/lyrics-bar.json");
    let fresh = build();
    let parsed: Value = serde_json::from_str(&fresh).unwrap();
    assert_eq!(parsed, contract(), "the file text is the contract");
    if std::env::var("UPDATE_GOLDEN").is_ok_and(|v| v == "1") {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let stored = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e} (run with UPDATE_GOLDEN=1 to create it)", path.display()));
    assert!(
        stored.replace("\r\n", "\n") == fresh,
        "{} is out of date: run UPDATE_GOLDEN=1 cargo test -p jf-ffi --test lyrics_bar_contract and review the diff",
        path.display()
    );
}

#[test]
fn the_ffi_gives_the_same_bar() {
    let (_, text) = CASES[0];
    let tl = timeline(text);
    let ffi = jf_ffi::lyrics_bar(tl.clone().into(), 1_250);
    let core = lyrics_bar(&tl, 1_250);
    assert_eq!(ffi.line, core.line.map(|l| l as u32));
    assert_eq!(ffi.next, core.next.map(|l| l as u32));
    assert_eq!(ffi.words, core.words);
}
