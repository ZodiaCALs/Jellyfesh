/// Bindings generated by `wit-bindgen` from `plugins/wit`. Most plugins only
/// need the re-exports in [`prelude`].
#[allow(unsafe_code, reason = "canonical ABI glue generated by wit-bindgen")]
#[allow(missing_debug_implementations, reason = "generated code")]
pub mod bindings {
    wit_bindgen::generate!({
        world: "remote-source",
        path: "../wit",
        pub_export_macro: true,
        export_macro_name: "__export_source_world",
        default_bindings_module: "jf_plugin_sdk::bindings",
        runtime_path: "jf_plugin_sdk::__private::wit_bindgen::rt",
        additional_derives: [PartialEq, serde::Serialize, serde::Deserialize],
    });
}

