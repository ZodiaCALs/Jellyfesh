//! Write Jellyfesh plugins in Rust.
//!
//! A plugin is a WebAssembly component for the `jellyfesh:plugin@1.1`
//! world `remote-source` (`plugins/wit`): the `source` world plus the
//! `remote` interface. This crate generates the bindings, turns a [`Plugin`]
//! implementation into the world's exports, and wraps the host imports in
//! small helpers. Plugins build for `wasm32-unknown-unknown` and end up with
//! **no WASI imports at all**.
//!
//! Hosts that implement API 1.0 load SDK 1.1 plugins as long as their
//! manifest says `api_version = "1.0"`: the extra `remote` export is never
//! looked up there. Declare `api_version = "1.1"` only for what needs it,
//! the `remote` capability and `[links]` (ADR-0018).
//!
//! # A plugin
//!
//! ```no_run
//! use jf_plugin_sdk::prelude::*;
//!
//! struct Example;
//!
//! impl Plugin for Example {
//!     fn capabilities() -> Vec<Capability> {
//!         vec![Capability::Search]
//!     }
//!
//!     fn search(query: String, _filters: SearchFilters, page: PageRequest) -> Result<ItemPage> {
//!         #[derive(serde::Deserialize)]
//!         struct Hit { id: String, title: String, artist: String, ms: u32 }
//!         let hits: Vec<Hit> = http::Request::get("https://api.example.com/search")
//!             .query(&[("q", &query), ("limit", &page.limit.to_string())])
//!             .send_json()?;
//!         let items = hits
//!             .into_iter()
//!             .map(|h| Item::new(ItemKind::Track, h.id, h.title).artist(h.artist).duration_ms(h.ms))
//!             .collect();
//!         Ok(ItemPage::new(items))
//!     }
//! }
//!
//! jf_plugin_sdk::export_plugin!(Example);
//! ```
//!
//! Everything a plugin does not implement answers
//! [`PluginError::Unsupported`]; the host only calls what the manifest
//! declares anyway. A remote-control plugin (`playback_mode = "remote"`)
//! implements the `remote_*` methods instead of [`Plugin::resolve_stream`]. Keep state between calls in `thread_local!` cells (a
//! plugin is single-threaded); the host may restart an instance at any time
//! (after a trap, a limit violation or a password login), so anything that
//! must survive goes to [`kv`] or, for credentials, [`kv::secret`].
//!
//! # Crate setup and building
//!
//! ```toml
//! [lib]
//! crate-type = ["cdylib"]
//!
//! [dependencies]
//! jf-plugin-sdk = { workspace = true }
//! serde = { workspace = true }
//! ```
//!
//! Build with `cargo xtask plugin build <package>` or `jf-plugin build`
//! (`tools/jf-plugin`; both share `jf-plugin-build`): it compiles for `wasm32-unknown-unknown` with
//! `--cfg getrandom_backend="custom"`, wraps the module into a component
//! with `wit-component`, checks that it imports nothing but
//! `jellyfesh:plugin/*@1`, and writes `target/plugins/<package>.wasm`. Pack it
//! with its `manifest.toml` into a `.jfpkg` (see `jf_plugin_host::package`).
//!
//! # What the SDK provides
//!
//! * [`http`]: a request builder with query and form encoding, JSON bodies,
//!   [`http::Request::send_json`], and status-to-error mapping;
//! * [`kv`]: plain values (with JSON helpers) and [`kv::secret`]s;
//! * [`crypto`]: digests, HMAC, AES, RSA encryption, RSA signing with a key
//!   from the keystore (API 1.1) and random bytes, done by the host;
//! * [`clock`]: wall and monotonic time (`std::time::SystemTime::now()`
//!   panics on this target);
//! * a `getrandom` backend over `crypto.random-bytes`, so crates such as
//!   `rand` or `uuid` work (getrandom 0.3 and 0.4 share the hook);
//! * logging macros ([`info!`], [`warn!`], …) and a panic hook that logs the
//!   panic message before the instance traps;
//! * [`PluginError`] conversions from every import's error type.

