// JVM compile check of the app's Kotlin; never shipped. Without an Android SDK (and with Google's
// Maven out of reach) the app module cannot build here, so this compiles app/src/main and
// app/src/ffi against stand-ins from Maven Central:
//
//  * Compose Multiplatform 1.8.2 for desktop: the runtime, foundation, ui and animation APIs of
//    Jetpack Compose 1.8 (newer releases pull Google-only androidx artifacts, so the app's 1.12
//    additions are not checked here);
//  * Robolectric's android-all: the Android framework classes;
//  * stubs (src/main/kotlin) of what exists only on Google's Maven or is Android-only: lifecycle
//    (repeatOnLifecycle, collectAsStateWithLifecycle, LocalLifecycleOwner), activity-compose,
//    core-ktx, browser, Compose's Android resources and context locals, and Cloudy 0.7.1's
//    backdrop API (signatures copied from its sources jar);
//  * an R class generated from app/src/main/res.
//
// It catches what a compiler catches (names, types, imports, Compose rules); it says nothing
// about runtime behaviour, and a stub that drifts from the real API hides a mistake. Media3 has
// no stand-in, so the playback package and MainActivity are left out. Present, like :ffi-check,
// once `cargo xtask bindings --lang kotlin` and `cargo xtask tokens --target kotlin` have run.
// Run: gradle :ui-check:compileKotlin (docs/android.md).
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("org.jetbrains.kotlin.jvm")
    id("org.jetbrains.kotlin.plugin.compose")
}

val androidDir: File = rootDir
val repoRoot: File = rootDir.resolve("../..").canonicalFile
val resDir: File = androidDir.resolve("app/src/main/res")

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_17
        freeCompilerArgs.add("-Xjsr305=strict")
    }
}

/** `R.string`, `R.plurals`, `R.drawable` and `R.mipmap` with made-up ids, from the app's resources. */
val generateR = tasks.register("generateR") {
    val out = layout.buildDirectory.dir("generated/r")
    inputs.dir(resDir)
    outputs.dir(out)
    doLast {
        val names = sortedMapOf<String, MutableSet<String>>()
        fun add(type: String, name: String) = names.getOrPut(type) { sortedSetOf() }.add(name)
        val valueTag = Regex("<(string|plurals|string-array|color|dimen|bool|integer)\\s+name=\"([A-Za-z0-9_]+)\"")
        resDir.listFiles().orEmpty().filter { it.isDirectory }.forEach { dir ->
            val type = dir.name.substringBefore('-')
            dir.listFiles().orEmpty().forEach { file ->
                if (type == "values") {
                    valueTag.findAll(file.readText()).forEach { m ->
                        val kind = when (val t = m.groupValues[1]) {
                            "string-array" -> "array"
                            else -> t
                        }
                        add(kind, m.groupValues[2])
                    }
                } else {
                    add(type, file.name.substringBefore('.'))
                }
            }
        }
        var id = 0x7f000000
        val text = buildString {
            appendLine("// Generated by :ui-check from app/src/main/res. Ids are made up.")
            appendLine("package org.jellyfesh.android")
            appendLine()
            appendLine("object R {")
            names.forEach { (type, set) ->
                appendLine("    object $type {")
                set.forEach { appendLine("        const val $it: Int = ${id++}") }
                appendLine("    }")
            }
            appendLine("}")
        }
        val file = out.get().asFile.resolve("org/jellyfesh/android/R.kt")
        file.parentFile.mkdirs()
        file.writeText(text)
    }
}

sourceSets {
    main {
        kotlin.srcDir(androidDir.resolve("app/src/main/kotlin"))
        kotlin.srcDir(androidDir.resolve("app/src/ffi/kotlin"))
        kotlin.srcDir(androidDir.resolve("core-bindings/src/main/kotlin"))
        kotlin.srcDir(repoRoot.resolve("platforms/shared/kotlin/src/main/kotlin"))
        kotlin.srcDir(generateR)
        kotlin.exclude("org/jellyfesh/android/playback/**", "org/jellyfesh/android/MainActivity.kt")
        // CoreConfigs.kt with or without CoreConfig.bundledPlugins (settings.gradle.kts).
        kotlin.srcDir(androidDir.resolve(gradle.extra["jellyfesh.ffiConfigDir"] as String))
    }
}

