#!/usr/bin/env python3
"""Android launcher icons from design/icons/round4 (ADR-0017).

For each of the ten colour options this writes an adaptive icon with a monochrome layer
(Android 13+ themed icons), named ic_launcher_<id>:

* background: a vector drawable (the tile's vertical gradient and its top glow; the SVG's 5 %
  noise grain is left out, it disappears at launcher sizes);
* foreground: for Ice and Steel, the two defaults, PNG layers rendered from the SVG geometry at
  every density with the blurred lift shadow ("full native icon sets"); for the other eight a
  vector drawable with the same strokes and gradient and a stepped shadow, so the APK grows by
  kilobytes;
* monochrome: a vector drawable of the glyph.

The SVGs are 1024 px canvases for a 108 dp adaptive layer; the glyph stays inside the 66 dp safe
circle. Needs Pillow (`pip install pillow`).

Usage: python3 platforms/android/scripts/gen_icons.py [repo-root]
"""
import json
import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, ImageFilter

SVG = "{http://www.w3.org/2000/svg}"
RASTER = ("ice", "steel")
DENSITIES = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
CANVAS = 1024
HEADER = "<!-- Generated by platforms/android/scripts/gen_icons.py from design/icons/round4. Do not edit. -->\n"


def res_name(icon_id):
    return icon_id.replace("-", "_")


def color(hex_color, opacity=1.0):
    """#rrggbb and an opacity as Android's #AARRGGBB."""
    h = hex_color.lstrip("#")
    a = max(0, min(255, round(float(opacity) * 255)))
    return f"#{a:02X}{h.upper()}"


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


# ---- reading the round 4 SVGs -------------------------------------------------------------------

def gradient_stops(element):
    return [(float(s.get("offset")), s.get("stop-color"), float(s.get("stop-opacity", "1"))) for s in element.iter(SVG + "stop")]


def read_background(path):
    root = ET.parse(path).getroot()
    linear = root.find(f".//{SVG}linearGradient")
    radial = root.find(f".//{SVG}radialGradient")
    return {
        "linear": {"y1": float(linear.get("y1")), "y2": float(linear.get("y2")), "stops": gradient_stops(linear)},
        "radial": {
            "cx": float(radial.get("cx")),
            "cy": float(radial.get("cy")),
            "r": float(radial.get("r")),
            "stops": gradient_stops(radial),
        },
    }


ARC = re.compile(r"M([\d.]+),([\d.]+) A([\d.]+),([\d.]+) 0 0 1 ([\d.]+),([\d.]+)( Z)?")
LINE = re.compile(r"M([\d.]+),([\d.]+) L([\d.]+),([\d.]+)")


def read_foreground(path):
    root = ET.parse(path).getroot()
    paint = root.find(f".//{SVG}linearGradient")
    mask = root.find(f".//{SVG}mask")
    shapes = []
    for p in mask.iter(SVG + "path"):
        d = p.get("d")
        filled = p.get("fill") not in (None, "none")
        width = float(p.get("stroke-width", "0"))
        luminance = rgb(p.get("stroke") if not filled else p.get("fill"))[0] / 255.0
        shapes.append({"d": d, "filled": filled, "width": width, "alpha": luminance})
    shadow_group = next(g for g in root.iter(SVG + "g") if g.get("filter"))
    shadow_path = next(shadow_group.iter(SVG + "path"))
    shadow_color = shadow_path.get("stroke") if shadow_path.get("stroke") not in (None, "none") else shadow_path.get("fill")
    dy = float(re.search(r"translate\(0 ([\d.]+)\)", shadow_group.get("transform")).group(1))
    blur = float(root.find(f".//{SVG}feGaussianBlur").get("stdDeviation"))
    return {
        "paint": {"y1": float(paint.get("y1")), "y2": float(paint.get("y2")), "stops": gradient_stops(paint)},
        "shapes": shapes,
        "shadow": {"color": shadow_color, "opacity": float(shadow_group.get("opacity")), "dy": dy, "blur": blur},
    }


def read_monochrome(path):
    root = ET.parse(path).getroot()
    out = []
    for p in root.iter(SVG + "path"):
        filled = p.get("fill") not in (None, "none")
        out.append({"d": p.get("d"), "filled": filled, "width": float(p.get("stroke-width", "0"))})
    return out


# ---- vector drawables ---------------------------------------------------------------------------

def vector(body):
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        + '    android:width="108dp"\n    android:height="108dp"\n'
        + f'    android:viewportWidth="{CANVAS}"\n    android:viewportHeight="{CANVAS}">\n'
        + body
        + "</vector>\n"
    )


def gradient_xml(attr, kind, geometry, stops, indent="        "):
    items = "".join(
        f'{indent}        <item android:offset="{o:g}" android:color="{color(c, a)}" />\n' for o, c, a in stops
    )
    return (
        f'{indent}<aapt:attr name="android:{attr}">\n'
        f'{indent}    <gradient android:type="{kind}" {geometry}>\n'
        f"{items}"
        f"{indent}    </gradient>\n"
        f"{indent}</aapt:attr>\n"
    )


def background_vector(bg):
    tile = "M0,0h1024v1024h-1024z"
    lin = bg["linear"]
    rad = bg["radial"]
    return vector(
        f'    <path android:pathData="{tile}">\n'
        + gradient_xml("fillColor", "linear", f'android:startX="0" android:startY="{lin["y1"]:g}" android:endX="0" android:endY="{lin["y2"]:g}"', lin["stops"])
        + "    </path>\n"
        + f'    <path android:pathData="{tile}">\n'
        + gradient_xml("fillColor", "radial", f'android:centerX="{rad["cx"]:g}" android:centerY="{rad["cy"]:g}" android:gradientRadius="{rad["r"]:g}"', rad["stops"])
        + "    </path>\n"
    )


def stroke_attrs(width):
    return f'android:strokeWidth="{width:g}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"'


def foreground_vector(fg):
    paint = fg["paint"]
    geometry = f'android:startX="0" android:startY="{paint["y1"]:g}" android:endX="0" android:endY="{paint["y2"]:g}"'
    shadow = fg["shadow"]
    body = ""
    # The SVG blurs a solid copy of the glyph (sigma 14) 16 px lower at 15-30 % opacity. Vector
    # drawables cannot blur, so three widening, fading copies approximate it.
    steps = [(shadow["blur"] * 2.0, 0.25), (shadow["blur"] * 1.2, 0.30), (shadow["blur"] * 0.4, 0.45)]
    body += f'    <group android:translateY="{shadow["dy"]:g}">\n'
    for extra, share in steps:
        alpha = shadow["opacity"] * share
        for s in fg["shapes"]:
            c = color(shadow["color"], alpha)
            if s["filled"]:
                body += f'        <path android:pathData="{s["d"]}" android:fillColor="{c}" android:strokeColor="{c}" android:strokeWidth="{extra:g}" android:strokeLineJoin="round" />\n'
            else:
                body += f'        <path android:pathData="{s["d"]}" android:strokeColor="{c}" {stroke_attrs(s["width"] + extra)} />\n'
    body += "    </group>\n"
    for s in fg["shapes"]:
        if s["filled"]:
            body += f'    <path android:pathData="{s["d"]}" android:fillAlpha="{s["alpha"]:.3f}">\n'
            body += gradient_xml("fillColor", "linear", geometry, paint["stops"])
        else:
            body += f'    <path android:pathData="{s["d"]}" android:strokeAlpha="{s["alpha"]:.3f}" {stroke_attrs(s["width"])}>\n'
            body += gradient_xml("strokeColor", "linear", geometry, paint["stops"])
        body += "    </path>\n"
    return vector(body)


def monochrome_vector(shapes):
    body = ""
    for s in shapes:
        if s["filled"]:
            body += f'    <path android:pathData="{s["d"]}" android:fillColor="#FF000000" />\n'
        else:
            body += f'    <path android:pathData="{s["d"]}" android:strokeColor="#FF000000" {stroke_attrs(s["width"])} />\n'
    return vector(body)


def adaptive_icon(rid, raster):
    foreground = f"@mipmap/ic_launcher_{rid}_foreground" if raster else f"@drawable/ic_launcher_{rid}_foreground"
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + HEADER
        + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        + f'    <background android:drawable="@drawable/ic_launcher_{rid}_background" />\n'
        + f'    <foreground android:drawable="{foreground}" />\n'
        + f'    <monochrome android:drawable="@drawable/ic_launcher_{rid}_monochrome" />\n'
        + "</adaptive-icon>\n"
    )


# ---- raster foregrounds (Ice and Steel) ---------------------------------------------------------

def draw_shape(draw, shape, scale, width_boost=0.0, offset_y=0.0, fill=255):
    d = shape["d"]
    w = (shape["width"] + width_boost) * scale
    m = ARC.fullmatch(d)
    if m:
        x1, y1, rx, _ry, x2, _y2, closed = m.groups()
        x1, y1, rx, x2 = float(x1), float(y1) + offset_y, float(rx), float(x2)
        cx = (x1 + x2) / 2 * scale
        cy = y1 * scale
        r = rx * scale
        if closed:
            grow = w / 2 if width_boost else 0
            draw.pieslice([cx - r - grow, cy - r - grow, cx + r + grow, cy + r + grow], 180, 360, fill=fill)
            if grow:
                draw.rectangle([cx - r - grow, cy - 1, cx + r + grow, cy + grow], fill=fill)
        else:
            draw.arc([cx - r - w / 2, cy - r - w / 2, cx + r + w / 2, cy + r + w / 2], 180, 360, fill=fill, width=max(1, round(w)))
            for ex in (cx - r, cx + r):
                draw.ellipse([ex - w / 2, cy - w / 2, ex + w / 2, cy + w / 2], fill=fill)
        return
    m = LINE.fullmatch(d)
    if m:
        x1, y1, x2, y2 = (float(v) for v in m.groups())
        y1 += offset_y
        y2 += offset_y
        draw.line([(x1 * scale, y1 * scale), (x2 * scale, y2 * scale)], fill=fill, width=max(1, round(w)))
        for x, y in ((x1, y1), (x2, y2)):
            draw.ellipse([x * scale - w / 2, y * scale - w / 2, x * scale + w / 2, y * scale + w / 2], fill=fill)
        return
    raise ValueError(f"unexpected path {d!r}")


def vertical_paint(size, scale, paint):
    """The glyph's paint: a vertical gradient between the paint's y1 and y2, clamped outside."""
    stops = [(o, rgb(c)) for o, c, _a in paint["stops"]]
    y1, y2 = paint["y1"] * scale, paint["y2"] * scale
    column = Image.new("RGB", (1, size))
    px = column.load()
    for y in range(size):
        t = 0.0 if y2 == y1 else min(1.0, max(0.0, (y - y1) / (y2 - y1)))
        for (o0, c0), (o1, c1) in zip(stops, stops[1:]):
            if t <= o1 or (o1, c1) == stops[-1]:
                k = 0.0 if o1 == o0 else min(1.0, max(0.0, (t - o0) / (o1 - o0)))
                px[0, y] = tuple(round(a + (b - a) * k) for a, b in zip(c0, c1))
                break
    return column.resize((size, size))


def raster_foreground(fg, size_master=2048):
    scale = size_master / CANVAS
    # Glyph mask: each shape at its own luminance (the SVG masks with #e6e6e6, 90 %).
    mask = Image.new("L", (size_master, size_master), 0)
    draw = ImageDraw.Draw(mask)
    for s in fg["shapes"]:
        draw_shape(draw, s, scale, fill=round(255 * s["alpha"]))
    glyph = vertical_paint(size_master, scale, fg["paint"]).convert("RGBA")
    glyph.putalpha(mask)
    # Lift shadow: a solid copy, lower, blurred, at the group's opacity.
    shadow_mask = Image.new("L", (size_master, size_master), 0)
    sdraw = ImageDraw.Draw(shadow_mask)
    for s in fg["shapes"]:
        draw_shape(sdraw, s, scale, offset_y=fg["shadow"]["dy"])
    shadow_mask = shadow_mask.filter(ImageFilter.GaussianBlur(fg["shadow"]["blur"] * scale))
    shadow_mask = shadow_mask.point(lambda v: round(v * fg["shadow"]["opacity"]))
    shadow = Image.new("RGBA", (size_master, size_master), rgb(fg["shadow"]["color"]) + (0,))
    shadow.putalpha(shadow_mask)
    layer = Image.new("RGBA", (size_master, size_master), (0, 0, 0, 0))
    layer = Image.alpha_composite(layer, shadow)
    return Image.alpha_composite(layer, glyph)


# ---- main ---------------------------------------------------------------------------------------

def main(repo):
    source = repo / "design/icons/round4"
    res = repo / "platforms/android/app/src/main/res"
    options = json.loads((source / "concepts.json").read_text())
    written = 0
    for option in options:
        icon_id = option["id"]
        rid = res_name(icon_id)
        folder = source / icon_id
        bg = read_background(folder / "background.svg")
        fg = read_foreground(folder / "foreground.svg")
        mono = read_monochrome(folder / "monochrome.svg")
        drawable = res / "drawable"
        drawable.mkdir(parents=True, exist_ok=True)
        (drawable / f"ic_launcher_{rid}_background.xml").write_text(background_vector(bg))
        (drawable / f"ic_launcher_{rid}_monochrome.xml").write_text(monochrome_vector(mono))
        raster = icon_id in RASTER
        if raster:
            master = raster_foreground(fg)
            for density, px in DENSITIES.items():
                out = res / f"mipmap-{density}"
                out.mkdir(parents=True, exist_ok=True)
                master.resize((px, px), Image.LANCZOS).save(out / f"ic_launcher_{rid}_foreground.png", optimize=True)
                written += 1
        else:
            (drawable / f"ic_launcher_{rid}_foreground.xml").write_text(foreground_vector(fg))
        anydpi = res / "mipmap-anydpi-v26"
        anydpi.mkdir(parents=True, exist_ok=True)
        (anydpi / f"ic_launcher_{rid}.xml").write_text(adaptive_icon(rid, raster))
        written += 3 if raster else 4
    print(f"wrote {written} icon files for {len(options)} icons into {res}")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[3]))
