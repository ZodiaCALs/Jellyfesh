#!/usr/bin/env python3
"""Write the first-frame theme (hue 250, both appearances) for the Windows app.

The core sends theme colours in its Theme slice, resolved from the artwork's hue (Misty
PLT-03). Before the first track plays that slice is empty, so the app starts with the colours
the core would resolve at the fallback hue. This script computes them exactly like jf-palette
(core/jf-palette/src/color.rs: OKLCH -> OKLab -> linear sRGB with the CSS Color 4 matrices,
per-channel clipping, f32 inputs, round half up) from the colour definitions in
core/jf-tokens/src/generated.rs, and writes FallbackTheme.cs.

Usage: python3 platforms/windows/scripts/fallback_theme.py
"""
import math
import pathlib
import re
import struct

ROOT = pathlib.Path(__file__).resolve().parents[3]
TOKENS = ROOT / "core/jf-tokens/src/generated.rs"
OUT = ROOT / "platforms/windows/src/Jellyfesh.Shared/Appearance/FallbackTheme.cs"
HUE = 250.0

OKLAB_TO_LMS = [
    [1.0, 0.3963377773761749, 0.2158037573099136],
    [1.0, -0.1055613458156586, -0.0638541728258133],
    [1.0, -0.0894841775298119, -1.2914855480194092],
]
LMS_TO_XYZ = [
    [1.2268798758459243, -0.5578149944602171, 0.2813910456659647],
    [-0.0405757452148008, 1.112286803280317, -0.0717110580655164],
    [-0.0763729366746601, -0.4214933324022432, 1.5869240198367816],
]
XYZ_TO_LINEAR_SRGB = [
    [12831.0 / 3959.0, -329.0 / 214.0, -1974.0 / 3959.0],
    [-851781.0 / 878810.0, 1648619.0 / 878810.0, 36519.0 / 878810.0],
    [705.0 / 12673.0, -2585.0 / 12673.0, 705.0 / 667.0],
]


def f32(x):
    return struct.unpack("f", struct.pack("f", x))[0]


def mul(m, v):
    return [m[i][0] * v[0] + m[i][1] * v[1] + m[i][2] * v[2] for i in range(3)]


def encode(v):
    a = abs(v)
    e = 1.055 * a ** (1 / 2.4) - 0.055 if a > 0.0031308 else 12.92 * a
    return math.copysign(e, v)


def quantize(v):
    return int(math.floor(min(max(v, 0.0), 1.0) * 255.0 + 0.5))


def resolve(l, c, h, alpha):
    hr = math.radians(h)
    lms = [x * x * x for x in mul(OKLAB_TO_LMS, [l, c * math.cos(hr), c * math.sin(hr)])]
    rgb = [min(max(encode(v), 0.0), 1.0) for v in mul(XYZ_TO_LINEAR_SRGB, mul(LMS_TO_XYZ, lms))]
    return [quantize(v) for v in rgb] + [quantize(alpha)]


def main():
    src = TOKENS.read_text()
    pattern = re.compile(
        r'name: "([^"]+)",\s*light: Lcha::(relative|fixed)\(([^)]*)\),\s*dark: Lcha::(relative|fixed)\(([^)]*)\)'
    )
    colors = {"light": {}, "dark": {}}
    for m in pattern.finditer(src):
        name = m.group(1)
        for appearance, kind, args in (("light", m.group(2), m.group(3)), ("dark", m.group(4), m.group(5))):
            l, c, h, a = (f32(float(x)) for x in args.split(","))
            hue = f32(f32(HUE) + h) if kind == "relative" else h
            colors[appearance][name] = resolve(l, c, hue, a)
    assert len(colors["light"]) > 30, "no colour definitions found"

    def table(appearance):
        rows = []
        for name in sorted(colors[appearance]):
            r, g, b, a = colors[appearance][name]
            rows.append(f'        ["{name}"] = new({r}, {g}, {b}, {a}),')
        return "\n".join(rows)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(f"""// @generated by platforms/windows/scripts/fallback_theme.py from core/jf-tokens/src/generated.rs.
// Do not edit by hand: rerun the script after `cargo xtask tokens`.

using Jellyfesh.Core;

namespace Jellyfesh.Appearance;

/// <summary>
/// The theme the core resolves at the fallback hue ({HUE:g}), for the first frame and whenever the
/// Theme slice is empty (nothing has played yet). Same conversion as jf-palette.
/// </summary>
public static class FallbackTheme
{{
    public const float Hue = {HUE:g}f;

    public static ThemeState Value {{ get; }} = new(
        Uid: null,
        Hue,
        FromArtwork: false,
        new ThemePalette(Hue, Core.Appearance.Light, Light),
        new ThemePalette(Hue, Core.Appearance.Dark, Dark),
        BackdropLight: null,
        BackdropDark: null);

    private static Dictionary<string, Rgba> Light => new()
    {{
{table("light")}
    }};

    private static Dictionary<string, Rgba> Dark => new()
    {{
{table("dark")}
    }};
}}
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(colors['light'])} colours per appearance)")


if __name__ == "__main__":
    main()
